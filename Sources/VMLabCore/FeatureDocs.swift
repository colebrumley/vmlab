import Foundation

/// Renders `docs/FEATURES.md` from the capability matrix, with a final column saying what the slow
/// probes found on the development host, read from the committed `docs/dev-host-facts.json`.
public enum FeatureDocs {
  /// The cell as Appendix B writes it: `Y`, `Y (note)`, `N`, `C \`fact\``, or `? \`probe\` (R-xxx)`.
  public static func cell(_ entry: Capabilities.Entry) -> String {
    switch entry.availability {
    case .yes: entry.note.map { "Y (\($0))" } ?? "Y"
    case .no: entry.note.map { "N (\($0))" } ?? "N"
    case .conditional(let condition):
      if let item = entry.verifiedBy {
        "? `\(condition.name)` (\(item))"
      } else {
        "C " + condition.names.map { "`\($0)`" }.joined(separator: " or ")
      }
    }
  }

  /// What the dev host's slow-probe snapshot says about the slow probes behind `feature`.
  public static func verified(_ feature: Feature, probes: SlowProbes) -> String {
    var seen: [SlowProbe] = []
    for profile in Profile.allCases {
      if case .conditional(let condition) = Capabilities.entry(feature, on: profile).availability {
        for probe in condition.probes where !seen.contains(probe) { seen.append(probe) }
      }
    }
    if seen.isEmpty { return "" }
    return seen.map { probe in
      let record = probes[probe]
      let date = record.probedAt.map { ", " + $0.formatted(.iso8601.year().month().day()) } ?? ""
      return "`\(probe.rawValue)`: \(record.result.rawValue)\(date)"
    }.joined(separator: "; ")
  }

  public static func markdown(probes: SlowProbes = SlowProbes()) -> String {
    let profiles = Profile.allCases
    var lines = [
      "# Features",
      "",
      "Generated by `scripts/gen-docs.sh` from `Sources/VMLabCore/Capabilities.swift`. Do not edit.",
      "",
      "Y yes; N no (the reason is in code and in refusals); C conditional on a host fact checked at",
      "every server start; ? conditional on a slow probe (the item that runs it is named). The last",
      "column is what the development host recorded (`docs/dev-host-facts.json`, refreshed with",
      "`scripts/gen-docs.sh --refresh-host-facts`); `unknown` counts as no.",
      "",
      "| Feature | " + profiles.map(\.rawValue).joined(separator: " | ")
        + " | verified on dev host |",
      "|---|" + String(repeating: "---|", count: profiles.count + 1),
    ]
    for feature in Feature.allCases {
      let cells = profiles.map { cell(Capabilities.entry(feature, on: $0)) }
      lines.append(
        "| `\(feature.rawValue)` | " + cells.joined(separator: " | ") + " | "
          + verified(feature, probes: probes) + " |")
    }
    func row(_ title: String, _ value: (Profile) -> String) {
      lines.append("| \(title) | " + profiles.map(value).joined(separator: " | ") + " |  |")
    }
    row("Guest OS") { Capabilities.guestOS(of: $0) == .macos ? "macOS" : "Linux" }
    row("Arch") { $0 == .qemuTCG ? "x86_64, arm64, riscv64, other" : "arm64" }
    row("Performance tier (1 best)") { String($0.performanceTier) }
    row("Energy tier (1 best)") { String($0.energyTier) }
    row("Startup tier (1 best)") { String($0.startupTier) }
    lines.append("")
    lines.append("## Reasons")
    lines.append("")
    for feature in Feature.allCases {
      for profile in profiles {
        if case .no(let reason) = Capabilities.entry(feature, on: profile).availability {
          lines.append("- `\(feature.rawValue)` on `\(profile.rawValue)`: \(reason).")
        }
      }
    }
    lines.append("")
    lines.append("## Engine notes")
    lines.append("")
    lines.append(contentsOf: engineNotes.map { "- " + $0 })
    lines.append("")
    return lines.joined(separator: "\n")
  }

  /// How each profile is realised where the matrix alone does not say.
  public static var engineNotes: [String] {
    let mac = ImageCatalogue.builtin.image(named: "macos-base")?.url ?? "macos-base"
    return [
      "`vz-macos` boots `tart clone`s of `macos-base` (`\(mac)`, which boots on the development "
        + "host, R-605) in vmlab's own `vmlab-vz` runner, built from the clone's `config.json`, "
        + "`nvram.bin` and `disk.img` (Tart 2.x layout); the `tart run --no-graphics` fallback is "
        + "not used, so pause and checkpoints are the runner's, as on `vz-linux`.",
      "`vz-linux` `serial` is the virtio console (`hvc0`); a disk boot boots the guest's own "
        + "default kernel, initrd and command line, read from its disk at every start, with "
        + "`VZLinuxBootLoader` and `console=hvc0` last, so the kernel's output is on serial from "
        + "the first boot (EFI and GRUB, with `console=hvc0` from the second boot, when the disk's "
        + "boot cannot be read). There is no early console: a panic before the virtio console "
        + "driver loads is not captured; `qemu-hvf` has a PL011 with `earlycon`.",
    ]
  }
}
