import Foundation
import VMLabCore

/// Renders `docs/TOOLS.md` from the tool schemas in `Sources/VMLabMCP/Tools/`.
public enum ToolDocs {
  public static func markdown() -> String {
    var out = """
      # Tools

      Generated by `scripts/gen-docs.sh` from `Sources/VMLabMCP/Tools/`. Do not edit.

      vmlab's MCP tools (Appendix C). Tool results are a JSON object; every result also carries
      `vm` (id and name) where a VM is involved and `warnings: [String]`. Errors are
      `{ code, message, hint, data }` with a code from Appendix D; any tool can also raise
      `internal`. Fields that only some actions use say so.


      """
    out += "| Tool | Summary |\n|---|---|\n"
    for tool in ToolCatalog.all {
      out += "| [`\(tool.name)`](#\(tool.name)) | \(cell(firstSentence(tool.summary))) |\n"
    }
    for tool in ToolCatalog.all {
      out += "\n## `\(tool.name)`\n\n\(tool.summary)\n\n"
      if !tool.errors.isEmpty {
        out += "**Errors:** " + tool.errors.map { "`\($0.rawValue)`" }.joined(separator: ", ")
        out += "\n\n"
      }
      out += "**Input**\n\n" + fieldTable(tool.inputSchema)
      out += "\n**Result**\n\n```\n\(tool.outputShape)\n```\n"
    }
    out += "\n## Requirements\n\n"
    out += "The `requirements` object of `vm_plan`, `vm_create` and `fleet` (`Requirements` in "
    out += "`Sources/VMLabCore/Features.swift`).\n\n"
    out += fieldTable(Schema.requirements)
    return out
  }

  /// One row per property, nested objects flattened to dotted paths, required fields first.
  static func fieldTable(_ schema: JSONValue) -> String {
    let rows = rows(schema, prefix: "")
    guard !rows.isEmpty else { return "None.\n" }
    var out = "| Field | Type | Required | Description |\n|---|---|---|---|\n"
    for row in rows {
      out += "| `\(row.path)` | \(cell(row.type)) | \(row.required ? "yes" : "") | "
      out += "\(cell(row.description)) |\n"
    }
    return out
  }

  private struct Row {
    var path: String
    var type: String
    var required: Bool
    var description: String
  }

  private static func rows(_ schema: JSONValue, prefix: String) -> [Row] {
    guard case .object(let node) = schema, case .object(let properties)? = node["properties"]
    else { return [] }
    let required = strings(node["required"])
    let names =
      required.filter { properties[$0] != nil }
      + properties.keys.filter { !required.contains($0) }.sorted()
    var out: [Row] = []
    for name in names {
      guard let property = properties[name] else { continue }
      let path = prefix + name
      let isRequirements = prefix.isEmpty && property == Schema.requirements
      out.append(
        Row(
          path: path, type: isRequirements ? "[requirements](#requirements)" : type(property),
          required: required.contains(name), description: field(property, "description")))
      if !isRequirements, case .object(let child) = property, child["properties"] != nil {
        out += rows(property, prefix: path + ".")
      }
      if case .object(let child) = property, let items = child["items"],
        case .object(let item) = items, item["properties"] != nil
      {
        out += rows(items, prefix: path + "[].")
      }
    }
    return out
  }

  /// e.g. `string`, `integer, 1–100, default 80`, `array of string`, `` `png` | `jpeg` ``.
  private static func type(_ schema: JSONValue) -> String {
    guard case .object(let node) = schema else { return "" }
    var text: String
    let enumValues = strings(node["enum"])
    if !enumValues.isEmpty {
      text = enumValues.map { "`\($0)`" }.joined(separator: " | ")
    } else if field(schema, "type") == "array", let items = node["items"] {
      text = "array of " + type(items)
    } else {
      text = field(schema, "type")
    }
    if field(schema, "type") == "array", let min = node["minItems"], min == node["maxItems"] {
      text += " (\(number(min)) items)"
    }
    var notes: [String] = []
    if field(schema, "type") == "array", node["minItems"] != node["maxItems"] {
      if let min = node["minItems"], let max = node["maxItems"] {
        notes.append("\(number(min))–\(number(max)) items")
      } else if let max = node["maxItems"] {
        notes.append("≤ \(number(max)) items")
      } else if let min = node["minItems"] {
        notes.append("≥ \(number(min)) items")
      }
    }
    if let length = node["maxLength"] { notes.append("≤ \(number(length)) characters") }
    if let minimum = node["minimum"] {
      notes.append(
        node["maximum"].map { "\(number(minimum))–\(number($0))" } ?? "≥ \(number(minimum))")
    } else if let maximum = node["maximum"] {
      notes.append("≤ \(number(maximum))")
    }
    if let value = node["default"] { notes.append("default `\(literal(value))`") }
    if !notes.isEmpty { text += ", " + notes.joined(separator: ", ") }
    return text
  }

  private static func field(_ schema: JSONValue, _ key: String) -> String {
    if case .object(let node) = schema, case .string(let value)? = node[key] { return value }
    return ""
  }

  private static func strings(_ value: JSONValue?) -> [String] {
    guard case .array(let items)? = value else { return [] }
    return items.compactMap { if case .string(let s) = $0 { s } else { nil } }
  }

  private static func number(_ value: JSONValue) -> String {
    if case .number(let n) = value { return n == n.rounded() ? String(Int(n)) : String(n) }
    return literal(value)
  }

  private static func literal(_ value: JSONValue) -> String {
    switch value {
    case .null: "null"
    case .bool(let b): String(b)
    case .number: number(value)
    case .string(let s): s
    case .array, .object: "…"
    }
  }

  private static func firstSentence(_ text: String) -> String {
    guard let end = text.range(of: ". ") else { return text }
    return String(text[..<end.lowerBound]) + "."
  }

  /// Escapes a Markdown table cell.
  private static func cell(_ text: String) -> String {
    text.replacingOccurrences(of: "|", with: "\\|").replacingOccurrences(of: "\n", with: " ")
  }
}
