import Foundation
import Testing

/// R-1102: no tool runs a host shell with model-supplied strings. Every host subprocess is a
/// `Process` with an executable and an argument array; the only `sh -c` in the tree runs *inside
/// the guest* (over SSH or the QEMU guest agent), with every word vmlab adds single-quoted.
@Suite struct HostShellTests {
  /// Files whose `sh -c` runs in the guest. None of them starts a host process: the command
  /// string they build is one argument to `ssh` (which hands it to the guest's shell) or the
  /// `arg` array of the agent's `guest-exec`.
  static let guestShellFiles: Set<String> = [
    "Sources/VMLabCore/RemoteShell.swift",
    "Sources/VMLabCore/Manifest.swift",
    "Sources/VMLabQEMU/GuestAgentExec.swift",
    // The io.vmlab.share LaunchDaemon's ProgramArguments (run by launchd in the guest).
    "Sources/VMLabVZ/MacProvisioning.swift",
  ]
  /// Files that name a shell only as cloud-config data for the guest (a login shell, a `runcmd`).
  static let cloudConfigFiles: Set<String> = ["Sources/VMLabCore/CloudInit.swift"]

  /// A string literal naming a shell, or `env` (which would run one).
  nonisolated(unsafe) static let shellLiteral =
    /"(?:\/(?:usr\/(?:local\/)?)?bin\/|\/opt\/homebrew\/bin\/)?(?:sh|bash|zsh|dash|ksh|fish|csh|tcsh)"|"\/usr\/bin\/env"/
  /// Host process launches.
  nonisolated(unsafe) static let launch =
    /Process\(\)|executableURL|HostProcess\.run|ProcessRunner\(|\.launchPath/
  /// APIs that go through a shell or around `Process`: never used.
  nonisolated(unsafe) static let banned =
    /(?:^|[^.\w])(?:system|popen)\((?!\w+:)|posix_spawn|NSTask|\bexec[lv]p?e?\(|\.launch\(\)/

  /// The code of a line, without a trailing `//` comment (string literals with `//` are rare
  /// enough here that the cut errs on the side of checking more).
  static func code(_ line: Substring) -> String {
    let text = String(line)
    if text.trimmingCharacters(in: .whitespaces).hasPrefix("//") { return "" }
    if let range = text.range(of: " // ") { return String(text[..<range.lowerBound]) }
    return text
  }

  /// What `source` (at `path`, relative to the package root) does wrong.
  static func violations(path: String, source: String) -> [String] {
    var found: [String] = []
    let lines = source.split(separator: "\n", omittingEmptySubsequences: false).map(code)
    let launchesHostProcesses = lines.contains { $0.contains(launch) }
    for (index, line) in lines.enumerated() {
      let at = "\(path):\(index + 1)"
      if line.contains(banned) { found.append("\(at): shell-capable API: \(line)") }
      guard line.contains(shellLiteral) else { continue }
      if line.contains(launch) {
        found.append("\(at): a shell as a host process executable: \(line)")
      } else if cloudConfigFiles.contains(path) {
        if line.contains("\"-c\"") { found.append("\(at): sh -c in cloud-config code: \(line)") }
      } else if guestShellFiles.contains(path) {
        if launchesHostProcesses {
          found.append("\(at): a guest-shell file also starts host processes")
        }
        // The script after `-c` is quoted, generated by RemoteShell, or a constant `…Script`
        // whose inputs follow it as arguments (on this line or the next).
        let window = line + (index + 1 < lines.count ? lines[index + 1] : "")
        if window.contains("\"-c\""), !window.contains("quote("), !window.contains("RemoteShell."),
          !window.contains(/"-c", \w+Script\b/)
        {
          found.append("\(at): sh -c with an unquoted script: \(line)")
        }
      } else {
        found.append("\(at): names a shell outside the guest-side files: \(line)")
      }
    }
    return found
  }

  @Test func noHostShellAnywhereInSources() throws {
    let root = BoundariesTests.root
    let sources = root.appending(path: "Sources")
    let enumerator = FileManager.default.enumerator(at: sources, includingPropertiesForKeys: nil)
    var found: [String] = []
    var seenGuestShell: Set<String> = []
    var files = 0
    while let url = enumerator?.nextObject() as? URL {
      guard url.pathExtension == "swift" else { continue }
      files += 1
      let path = url.path.replacingOccurrences(of: root.path + "/", with: "")
      let source = try String(contentsOf: url, encoding: .utf8)
      found += Self.violations(path: path, source: source)
      if source.split(separator: "\n").map(Self.code).contains(where: {
        $0.contains(Self.shellLiteral)
      }) {
        seenGuestShell.insert(path)
      }
    }
    #expect(files > 50)
    #expect(found == [])
    // The allowlist stays exact: a file that stops naming a shell leaves it.
    #expect(seenGuestShell == Self.guestShellFiles.union(Self.cloudConfigFiles))
  }

  @Test func checkerCatchesHostShells() {
    let planted = """
      let process = Process()
      process.executableURL = URL(filePath: "/bin/sh")
      process.arguments = ["-c", "ls \\(userPath)"]
      """
    #expect(Self.violations(path: "Sources/X/Y.swift", source: planted).count == 1)
    let viaRunner = #"try runner.run("/bin/bash", ["-c", command])"#
    #expect(!Self.violations(path: "Sources/X/Y.swift", source: viaRunner).isEmpty)
    let env = #"let tool = "/usr/bin/env""#
    #expect(!Self.violations(path: "Sources/X/Y.swift", source: env).isEmpty)
    #expect(!Self.violations(path: "Sources/X/Y.swift", source: "let r = system(cmd)").isEmpty)
    let unquoted = #"let words = ["sh", "-c", script]"#
    #expect(!Self.violations(path: "Sources/VMLabCore/RemoteShell.swift", source: unquoted).isEmpty)
    let quoted = #"let words = ["/bin/sh", "-c", quote(script)]"#
    #expect(Self.violations(path: "Sources/VMLabCore/RemoteShell.swift", source: quoted).isEmpty)
    let comment = "/// Runs `/bin/sh -c` in the guest. \"sh\""
    #expect(Self.violations(path: "Sources/X/Y.swift", source: comment).isEmpty)
  }
}
